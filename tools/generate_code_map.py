"""Generate REFACTOR_DOCUMENTATION.md: each module of src/tarel as input, processing, output.

The map is derived from the code itself so it cannot drift silently:

- purpose: the module docstring;
- input: parameters of the public functions and methods, plus the sources the module reads
  (stores, files, network, databases, stdin, environment);
- processing: each public function, method and class with the first line of its docstring;
- output: return types, plus the effects the module has (store writes, files, printed output,
  network calls).

Run ``python tools/generate_code_map.py`` after changing modules and commit the result;
``--check`` fails when the committed file is stale.
"""

from __future__ import annotations

import ast
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "tarel"
OUTPUT = ROOT / "REFACTOR_DOCUMENTATION.md"

# Method calls (obj.name(...)) and function calls (name(...)) that reveal reads and writes.
READ_METHODS = {
    "load": "loads stored documents", "read_text": "reads files", "read_bytes": "reads files",
    "connect": "opens database connections", "getenv": "reads environment variables",
}
READ_FUNCTIONS = {"urlopen": "calls HTTP endpoints", "load_settings": "reads retrieval settings"}
READ_ATTRIBUTES = {"stdin": "reads stdin", "environ": "reads environment variables"}
WRITE_METHODS = {
    "save": "saves documents to a store",
    "write_text": "writes files",
    "write_bytes": "writes files",
    "unlink": "deletes files",
    "execute": "runs database queries",
    "mkstemp": "writes temporary files",
}
WRITE_FUNCTIONS = {
    "write_atomic": "replaces state files atomically",
    "print": "prints to the terminal",
    "print_json": "prints JSON to stdout",
    "urlopen": "sends HTTP requests",
}


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print("REFACTOR_DOCUMENTATION.md is stale. Run python tools/generate_code_map.py")
            return 1
        print(f"Code map current: {text.count(chr(10) + '### ')} modules.")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


def render() -> str:
    modules = sorted(SOURCE.rglob("*.py"))
    used_by = _reverse_imports(modules)
    lines = [
        "# TAREL code map",
        "",
        "Every module in `src/tarel`, described as input, processing and output (EVA: Eingabe,",
        "Verarbeitung, Ausgabe). Generated by `tools/generate_code_map.py` from docstrings,",
        "signatures and calls; do not edit by hand.",
        "",
        "How to read an entry:",
        "",
        "- **Input** lists what callers pass in and which sources the module reads.",
        "- **Processing** lists the public functions, methods and classes with their purpose.",
        "- **Output** lists return types and the effects on state, files, terminal or network.",
        "- **Uses** and **Used by** name the TAREL modules it imports and that import it.",
        "",
        "## Packages",
        "",
        "| Package | Purpose |",
        "| --- | --- |",
    ]
    for package in sorted(path for path in SOURCE.iterdir() if (path / "__init__.py").is_file()):
        doc = _first_line(ast.get_docstring(ast.parse((package / "__init__.py").read_text())))
        lines.append(f"| `tarel.{package.name}` | {doc} |")
    current_package = None
    for path in modules:
        module = _module_name(path)
        package = module.split(".")[1] if module.count(".") > 1 else "tarel"
        if package != current_package:
            current_package = package
            lines += ["", f"## `{'tarel' if package == 'tarel' else 'tarel.' + package}`"]
        lines += ["", *_module_entry(path, module, used_by.get(module, set()))]
    return "\n".join(lines) + "\n"


def _module_entry(path: Path, module: str, used_by: set[str]) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    relative = path.relative_to(ROOT).as_posix()
    entry = [f"### `{relative}`", "", _first_paragraph(ast.get_docstring(tree)) or "No docstring."]
    functions = list(_public_callables(tree))
    inputs = sorted(
        {f"`{name}: {annotation}`" for _, args in functions for name, annotation in args}
    )
    returns = sorted({result for _, _, result in _signatures(tree) if result not in {"None", ""}})
    reads, writes = _effects(tree)
    entry += [
        "",
        "- **Input:** "
        + _join(
            (
                ["parameters " + ", ".join(inputs[:12]) + (" …" if len(inputs) > 12 else "")]
                if inputs
                else []
            )
            + reads,
            "none (constants or declarations only)",
        ),
    ]
    processing = [f"`{name}`: {summary}" for name, summary in _summaries(tree)]
    if processing:
        entry.append("- **Processing:**")
        entry += [f"    - {item}" for item in processing]
    else:
        entry.append("- **Processing:** module-level constants and imports only.")
    entry.append(
        "- **Output:** "
        + _join(
            (["returns " + ", ".join(f"`{item}`" for item in returns[:10])] if returns else [])
            + writes,
            "no return values or effects",
        )
    )
    uses = sorted(_tarel_imports(tree) - {module})
    if uses:
        entry.append("- **Uses:** " + ", ".join(f"`{item}`" for item in uses))
    if used_by:
        entry.append("- **Used by:** " + ", ".join(f"`{item}`" for item in sorted(used_by)))
    return entry


def _public_callables(tree: ast.Module):
    """(name, [(parameter, annotation), ...]) for public functions and public methods."""
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            yield node.name, _parameters(node)
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                    yield f"{node.name}.{item.name}", _parameters(item)


def _parameters(node: ast.FunctionDef) -> list[tuple[str, str]]:
    arguments = node.args.posonlyargs + node.args.args + node.args.kwonlyargs
    return [
        (arg.arg, ast.unparse(arg.annotation) if arg.annotation else "Any")
        for arg in arguments
        if arg.arg not in {"self", "cls"}
    ]


def _signatures(tree: ast.Module):
    for name, _ in _public_callables(tree):
        node = _find(tree, name)
        yield name, node, ast.unparse(node.returns) if node and node.returns else ""


def _find(tree: ast.Module, dotted: str) -> ast.FunctionDef | None:
    owner, _, method = dotted.partition(".")
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == owner and not method:
            return node
        if isinstance(node, ast.ClassDef) and node.name == owner:
            return next(
                (
                    item
                    for item in node.body
                    if isinstance(item, ast.FunctionDef) and item.name == method
                ),
                None,
            )
    return None


def _summaries(tree: ast.Module) -> list[tuple[str, str]]:
    imported = _imported_names(tree)
    rows = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and _documented(node.name):
            kind = "class" if isinstance(node, ast.ClassDef) else "function"
            summary = _first_line(ast.get_docstring(node)) or _describe(node, kind)
            rows.append((node.name, summary + _calls(node, imported)))
            if isinstance(node, ast.ClassDef):
                for item in node.body:
                    if isinstance(item, ast.FunctionDef) and _documented(item.name):
                        summary = _first_line(ast.get_docstring(item)) or _describe(item, "method")
                        rows.append((f"{node.name}.{item.name}", summary + _calls(item, imported)))
    return rows


def _documented(name: str) -> bool:
    """Public names plus the private CLI (_run_*) and browser route (_post_*) handlers."""
    return not name.startswith("_") or name.startswith(("_run_", "_post_"))


def _imported_names(tree: ast.Module) -> set[str]:
    return {
        alias.asname or alias.name
        for node in tree.body
        if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("tarel")
        for alias in node.names
    }


def _calls(node: ast.AST, imported: set[str]) -> str:
    """' Calls `a`, `b`; uses the graph store.' for functions; empty for records."""
    if isinstance(node, ast.ClassDef):
        return ""
    calls, raises, stores = [], [], []
    for item in ast.walk(node):
        if not isinstance(item, ast.Call):
            continue
        if isinstance(item.func, ast.Name) and item.func.id in imported:
            failure = item.func.id.endswith(("Failure", "Error"))
            (raises if failure else calls).append(item.func.id)
        elif isinstance(item.func, ast.Attribute) and item.func.attr.endswith(("_store", "_index")):
            stores.append(item.func.attr.replace("_", " "))
    calls = list(dict.fromkeys(name for name in calls if name != "resolve_runtime"))
    parts = []
    if calls:
        shown = ", ".join(f"`{name}`" for name in calls[:6])
        parts.append(f"calls {shown}{' …' if len(calls) > 6 else ''}")
    if stores:
        parts.append("uses the " + ", ".join(dict.fromkeys(stores)))
    if raises:
        parts.append("raises " + ", ".join(f"`{name}`" for name in dict.fromkeys(raises)))
    text = "; ".join(parts)
    return f" {text[:1].upper()}{text[1:]}." if text else ""


def _describe(node: ast.AST, kind: str) -> str:
    """A factual fallback when there is no docstring: what the signature says."""
    if isinstance(node, ast.ClassDef):
        fields = [
            item.target.id
            for item in node.body
            if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name)
        ]
        bases = ", ".join(ast.unparse(base) for base in node.bases)
        if fields:
            return f"record with fields {', '.join(fields[:8])}{' …' if len(fields) > 8 else ''}."
        return f"class based on {bases}." if bases else "class."
    assert isinstance(node, ast.FunctionDef)
    result = ast.unparse(node.returns) if node.returns else "None"
    words = node.name.removesuffix("_use_case").removeprefix("_run_").removeprefix("_post_")
    words = words.replace("_", " ")
    suffix = " (use case)" if node.name.endswith("_use_case") else ""
    return f"{words}{suffix}; returns `{result}`."


def _effects(tree: ast.AST) -> tuple[list[str], list[str]]:
    methods, functions, attributes = set(), set(), set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
            methods.add(node.func.attr)
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            functions.add(node.func.id)
        elif isinstance(node, ast.Attribute):
            attributes.add(node.attr)
    reads = {text for name, text in READ_METHODS.items() if name in methods}
    reads |= {text for name, text in READ_FUNCTIONS.items() if name in functions}
    reads |= {text for name, text in READ_ATTRIBUTES.items() if name in attributes}
    writes = {text for name, text in WRITE_METHODS.items() if name in methods}
    writes |= {text for name, text in WRITE_FUNCTIONS.items() if name in functions}
    return sorted(reads), sorted(writes)


def _tarel_imports(tree: ast.Module) -> set[str]:
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module and node.module.startswith("tarel"):
            names.add(node.module)
        elif isinstance(node, ast.Import):
            names |= {alias.name for alias in node.names if alias.name.startswith("tarel")}
    return names


def _reverse_imports(modules: list[Path]) -> dict[str, set[str]]:
    used_by: dict[str, set[str]] = defaultdict(set)
    for path in modules:
        module = _module_name(path)
        for imported in _tarel_imports(ast.parse(path.read_text(encoding="utf-8"))):
            if imported != module:
                used_by[imported].add(module)
    return used_by


def _module_name(path: Path) -> str:
    parts = path.relative_to(SOURCE.parent).with_suffix("").parts
    return ".".join(parts[:-1] if parts[-1] == "__init__" else parts)


def _first_line(doc: str | None) -> str:
    return doc.strip().split("\n")[0].strip() if doc else ""


def _first_paragraph(doc: str | None) -> str:
    return " ".join(doc.strip().split("\n\n")[0].split()) if doc else ""


def _join(items: list[str], empty: str) -> str:
    return "; ".join(items) if items else empty


if __name__ == "__main__":
    sys.exit(main())
